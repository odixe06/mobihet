"""Freeze schema/scaler-derived atoms into source; no learned auxiliary model."""
import hashlib
import json
from pathlib import Path
ROOT=next((p for p in Path(__file__).resolve().parents if (p/'CONTEXT.md').is_file()), Path(__file__).resolve().parents[1])
meta=ROOT/'knowledge/meta.json'; scale=ROOT/'knowledge/scaler.json'
schema=ROOT.parent/'dataset/centralized/feature_schema.json'
cols=json.loads(meta.read_text())['feature_cols']; scaler=json.loads(scale.read_text())['features']
raw=json.loads(schema.read_text()); assert cols==raw['feature_columns']
values=dict(ATOM0=[-scaler[c]['mean']/scaler[c]['std_used'] for c in cols],
    ATOM1=[(1-scaler[c]['mean'])/scaler[c]['std_used'] for c in cols],
    FIRST=cols.index('f_first_in_session'),
    PROFILES=[[cols.index(f'f_{side}_profile_{name}') for name in ('normal','cautious','aggressive')] for side in ('rcv','snd')],
    STRUCTURAL=[cols.index(c) for c in raw['zero_imputed_features']],
    PROVENANCE={p.name:hashlib.sha256(p.read_bytes()).hexdigest() for p in (meta,scale,schema)})
content='"""Fixed train scaler/schema atoms; generated by scripts/freeze_v4_schema.py."""\n'
content+='\n'.join(f'{k} = {v!r}' for k,v in values.items())+'\n'
out=ROOT/'mh/v4_schema.py'; assert not out.exists(),'do not overwrite frozen source'
out.write_text(content); print('Frozen source schema:',len(cols),'features',len(values['STRUCTURAL']),'structural atoms')
