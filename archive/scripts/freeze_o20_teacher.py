"""Freeze audited train-only N0/N1 teachers and equivalent fp16 downlinks; never raw client data."""
import base64
import hashlib
import json
from pathlib import Path
import zlib

import numpy as np
import torch


def main():
    target = Path("methods/mobihet_replay_data.py")
    assert not target.exists(), "Frozen input exists; do not overwrite"
    batch = json.loads(Path("runs/n-study/batch.json").read_text())[:2]
    receipts = {r["arm"]: r for r in json.loads(Path("runs/n-study/collection/diagnostic-audit.json").read_text())}
    tables, packets, sources = [], [], []
    for spec in batch:
        history, bodies = [], []
        for r in range(1, 21):
            path = Path("artifacts/n20") / spec["slug"] / spec["slug"] / "models" / f"r{r:03}.pt"
            assert hashlib.sha256(path.read_bytes()).hexdigest() == receipts[spec["arm"]]["snapshots"][r - 1]["sha256"]
            q = torch.load(path, weights_only=True, map_location="cpu", mmap=True)["Q"].numpy().copy()
            body = np.empty_like(q, dtype=np.float16)
            for c, row in enumerate(q):
                value = np.float16(row.max()); up = down = value; candidates = [value]
                for _ in range(8):
                    up = np.nextafter(up, np.float16(np.inf)); down = np.nextafter(down, np.float16(-np.inf))
                    candidates.extend((up, down))
                for device in ("cpu", "cuda"):
                    found = False
                    for value in candidates:
                        candidate = (row * (np.float32(value) / row.max())).astype(np.float16)
                        t = torch.from_numpy(candidate).to(device).float()
                        if np.array_equal((t / t.sum()).cpu().numpy(), row):
                            body[c] = candidate; found = True; break
                    if found: break
                assert found, (spec["arm"], r, c)
            decoded = torch.from_numpy(body).cuda().float()
            assert np.array_equal((decoded / decoded.sum(-1, keepdim=True)).cpu().numpy(), q)
            history.append(q); bodies.append(body)
        tables.append(history); packets.append(bodies)
        sources.append({"seed": 42 + len(sources), "ref": f'{spec["account"]}/{spec["slug"]}/1',
                        "snapshots": receipts[spec["arm"]]["snapshots"]})
    raw = np.asarray(tables, dtype="<f4").tobytes() + np.asarray(packets, dtype="<f2").tobytes()
    digest = hashlib.sha256(raw).hexdigest()
    target.write_text('"""Frozen N0/N1 train-only aggregate teachers. Generated by freeze_o20_teacher.py; do not edit."""\n'
                      + f"SHA256 = {digest!r}\nSOURCES = {sources!r}\nPAYLOAD = {base64.b64encode(zlib.compress(raw)).decode()!r}\n")
    out = Path("runs/o-study"); out.mkdir(exist_ok=True)
    (out / "teacher-source.json").write_text(json.dumps({"sha256": digest, "decoded_bytes": len(raw),
        "sources": sources, "scope": "Equivalent fp16 bodies verified exact decoded Q on local GPU; not original packet identity or T4 proof"}, indent=2) + "\n")
    print("O20_TEACHER_FROZEN", digest)


if __name__ == "__main__": main()
